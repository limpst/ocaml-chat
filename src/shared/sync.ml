(* =========================================================================
   Sync — 스레드 동기화 도우미 (서버 전용 공용 모듈)
   -------------------------------------------------------------------------
   서버는 클라이언트마다 스레드를 하나씩 띄우므로, 여러 스레드가 같은
   데이터(채팅방, 파일, 소켓)에 동시에 접근한다. 이 모듈은 "잠그고 → 실행하고
   → 반드시 푼다"는 패턴을 한 곳에 모아 실수(잠금 해제 누락)를 막는다.
   ========================================================================= *)

(* [with_lock mutex action]
   mutex 를 잠근 상태에서 action () 을 실행하고 그 결과를 돌려준다.
   action 이 예외를 던져도 finally 덕분에 잠금은 항상 해제된다. *)
let with_lock (mutex : Mutex.t) (action : unit -> 'a) : 'a =
  Mutex.lock mutex;                                  (* 1. 잠금 획득 (다른 스레드는 여기서 대기) *)
  Fun.protect                                        (* 2. action 실행을 보호 블록으로 감싼다 *)
    ~finally:(fun () -> Mutex.unlock mutex)          (* 3. 정상 종료든 예외든 마지막에 잠금 해제 *)
    action                                           (* 4. 실제로 실행할 작업 *)
